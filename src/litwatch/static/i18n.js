  const storedLocale = () => {
    try {
      const value = window.localStorage.getItem(STORAGE_KEY);
      return SUPPORTED_LOCALES.has(value) ? value : DEFAULT_LOCALE;
    } catch (_error) {
      return DEFAULT_LOCALE;
    }
  };

  const format = (message, params) => message.replace(/\{(\w+)\}/g, (_match, key) => (
    Object.hasOwn(params, key) ? String(params[key]) : `{${key}}`
  ));

  const t = (key, params = {}) => {
    const locale = storedLocale();
    const message = messages[locale]?.[key] ?? messages.en[key] ?? key;
    return format(message, params);
  };

  const translatePage = () => {
    const locale = storedLocale();
    document.documentElement.lang = locale;
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = t(element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
    });
    document.querySelectorAll("[data-locale]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.locale === locale));
    });
  };

  const setLocale = (locale) => {
    if (!SUPPORTED_LOCALES.has(locale)) return;
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch (_error) {
      return;
    }
    window.location.reload();
  };

  document.addEventListener("DOMContentLoaded", () => {
    translatePage();
    document.querySelectorAll("[data-locale]").forEach((button) => {
      button.addEventListener("click", () => setLocale(button.dataset.locale));
    });
  });

  window.LitWatchI18n = Object.freeze({
    defaultLocale: DEFAULT_LOCALE,
    locale: storedLocale,
    setLocale,
    t,
    translatePage,
  });
